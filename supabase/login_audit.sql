-- SFW login activity audit.
-- Run after supabase/schema.sql in the Supabase SQL Editor.
-- No service-role key is used by the Streamlit app.

create table if not exists public.sfw_login_events (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    email text not null,
    event_type text not null check (event_type in ('sign_in', 'sign_up')),
    created_at timestamptz not null default now()
);

create index if not exists sfw_login_events_created_idx
    on public.sfw_login_events (created_at desc);
create index if not exists sfw_login_events_user_created_idx
    on public.sfw_login_events (user_id, created_at desc);

alter table public.sfw_login_events enable row level security;

drop policy if exists "Users can record their own SFW login events" on public.sfw_login_events;
create policy "Users can record their own SFW login events"
    on public.sfw_login_events for insert to authenticated
    with check (auth.uid() = user_id);

drop policy if exists "Admins can read SFW login events" on public.sfw_login_events;
create policy "Admins can read SFW login events"
    on public.sfw_login_events for select to authenticated
    using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

grant insert, select on public.sfw_login_events to authenticated;
grant usage, select on sequence public.sfw_login_events_id_seq to authenticated;

